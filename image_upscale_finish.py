"""Natural-looking photo upscale postprocessing with the existing ESRGAN runtime.

No new models or downloads. Blend the original at target resolution with the
neural result to preserve scene appearance and reduce waxy-looking surfaces.
Explicit crisp mode adds modest edge enhancement; legacy presets are unchanged.
"""
from pathlib import Path

# Blend factors are fixed per mode, not arbitrary client-supplied knobs.
# 0 is pure resampled original, 1 is unchanged ESRGAN output.
PHOTO_FINISH = {
    "photo-natural-2x": (0.55, False),
    "photo-natural-4x": (0.60, False),
    "photo-sharp-4x": (0.82, True),
}


def finish_photo_upscale(source, output, preset):
    """Postprocess in place. Leave legacy/illustration modes byte-for-byte alone.

    Output dimensions are dictated by the Real-ESRGAN runtime, never by this
    finishing pass. An RGB/RGBA conversion handles grayscale/palette inputs
    without modifying the original source on disk.
    """
    finish = PHOTO_FINISH.get(preset)
    if finish is None:
        return False
    from PIL import Image, ImageFilter

    blend_weight, sharpen = finish
    source = Path(source)
    output = Path(output)
    with Image.open(source) as original, Image.open(output) as generated:
        mode = "RGBA" if ("A" in original.getbands() or "A" in generated.getbands()) else "RGB"
        original_resized = original.convert(mode).resize(
            generated.size, resample=Image.Resampling.LANCZOS,
        )
        ai_output = generated.convert(mode)
        result = Image.blend(original_resized, ai_output, blend_weight)
        if sharpen:
            # Mild edge contrast with threshold avoids amplifying flat skin.
            result = result.filter(ImageFilter.UnsharpMask(
                radius=1.0, percent=70, threshold=5,
            ))
        if mode == "RGBA":
            # Keep the source transparency mask consistent rather than blending
            # in an opaque alpha channel generated by the upscaler.
            result.putalpha(original_resized.getchannel("A"))
        # Preserve source files and publish via the existing finalization path.
        result.save(output, format="PNG")
    return True
